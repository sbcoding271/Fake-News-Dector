import pandas as pd
from sklearn.model_selection import train_test_split
from sklearn.feature_extraction.text import TfidfVectorizer
from sklearn.linear_model import LogisticRegression
from sklearn.metrics import classification_report
import re
import joblib
import string

"""Loading datasets into Pandas"""

fake= pd.read_csv('/content/Fake.csv', on_bad_lines='skip', engine='python')
true= pd.read_csv('/content/True.csv', on_bad_lines='skip', engine='python')

fake.head()

true.head()

fake['class']=0
true['class']=1

data= pd.concat([fake,true],axis=0)

data.sample(10)

data= data.drop(["title","subject","date"],axis = 1)

data.reset_index(inplace=True)

data.drop(["index"],axis=1,inplace=True)

data.sample(5)

"""Creating your won function for cleaning the dataset"""

def clean_text(text):
    text = str(text).lower() # Ensure output is string
    text = re.sub('\[.*?\]', '', text)
    text= re.sub("\\W"," ",text)
    text = re.sub('https?://\S+|www\.\S+', '', text)
    text = re.sub('<.*?>+', '', text)
    text= re.sub('[%s]' % re.escape(string.punctuation), '', text)
    text = re.sub('\n', '', text)
    text = re.sub('\w*\d\w*', '', text)
    return text

"""Adding the above function for cleaning the dataset"""

data["text"]=data["text"].apply(clean_text)

"""Splitting the Datasets into Training & Testing"""

x=data["text"]
y=data["class"]

xtrain,xtest,ytrain,ytest=train_test_split(x,y,test_size=0.25,random_state=42)

"""Converting the cleaned data into number format using vectorizer function"""

vectorizer=TfidfVectorizer()
xv_train=vectorizer.fit_transform(xtrain)
xv_test=vectorizer.transform(xtest)

"""Training the model"""

model=LogisticRegression()
model.fit(xv_train,ytrain)

"""Converting all the numerical data into String Format"""

data['text'] = data['text'].astype(str)

"""Using the trained model for making the predections"""

predection=model.predict(xv_test)

"""Checking accuracy of the model"""

print(model.score(xv_test,ytest))

print(classification_report(ytest,predection))

joblib.dump(vectorizer,"vectorizer.jb")
joblib.dump(model,"model.jb")

# 🔹 Take input text (can be replaced or extended later)
input_text = "On Christmas day, Donald Trump announced that he would  be back to work  the following day, but he is golfing for the fourth day in a row."
# 🔹 Transform using saved vectorizer
new_input = vectorizer.transform([input_text])

# 🔹 Predict using the model
prediction = model.predict(new_input)

# 🔹 Print readable result
if prediction[0] == 0:
    print("🟥 Prediction: FAKE NEWS ❌")
else:
    print("🟩 Prediction: REAL NEWS ✅")

proba = model.predict_proba(new_input)
print(f"🟥 Fake: {proba[0][0]*100:.2f}% | 🟩 Real: {proba[0][1]*100:.2f}%")